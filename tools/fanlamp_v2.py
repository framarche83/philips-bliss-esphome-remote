"""FanLamp Pro V2 codec (service data UUID 0x08F0, header F0 08), as used by the Philips Bliss remote.

Derived from NicoIIT/ha-ble-adv codecs/fanlamp.py (MIT License). Needs pycryptodome.
"""
from binascii import crc_hqx

from Crypto.Cipher import AES

XBOXES = [
    0xB7, 0xFD, 0x93, 0x26, 0x36, 0x3F, 0xF7, 0xCC, 0x34, 0xA5, 0xE5, 0xF1, 0x71, 0xD8, 0x31, 0x15,
    0x04, 0xC7, 0x23, 0xC3, 0x18, 0x96, 0x05, 0x9A, 0x07, 0x12, 0x80, 0xE2, 0xEB, 0x27, 0xB2, 0x75,
    0xD0, 0xEF, 0xAA, 0xFB, 0x43, 0x4D, 0x33, 0x85, 0x45, 0xF9, 0x02, 0x7F, 0x50, 0x3C, 0x9F, 0xA8,
    0x51, 0xA3, 0x40, 0x8F, 0x92, 0x9D, 0x38, 0xF5, 0xBC, 0xB6, 0xDA, 0x21, 0x10, 0xFF, 0xF3, 0xD2,
    0xE0, 0x32, 0x3A, 0x0A, 0x49, 0x06, 0x24, 0x5C, 0xC2, 0xD3, 0xAC, 0x62, 0x91, 0x95, 0xE4, 0x79,
    0xE7, 0xC8, 0x37, 0x6D, 0x8D, 0xD5, 0x4E, 0xA9, 0x6C, 0x56, 0xF4, 0xEA, 0x65, 0x7A, 0xAE, 0x08,
    0xE1, 0xF8, 0x98, 0x11, 0x69, 0xD9, 0x8E, 0x94, 0x9B, 0x1E, 0x87, 0xE9, 0xCE, 0x55, 0x28, 0xDF,
    0x8C, 0xA1, 0x89, 0x0D, 0xBF, 0xE6, 0x42, 0x68, 0x41, 0x99, 0x2D, 0x0F, 0xB0, 0x54, 0xBB, 0x16,
]  # fmt: skip


def _whiten(buf, seed8: int, salt: int) -> bytearray:
    return bytearray(XBOXES[((seed8 + i + 9) & 0x1F) + salt] ^ seed8 ^ v for i, v in enumerate(buf))


def _sign(buf, tx: int, seed: int) -> int:
    key = bytes([seed & 0xFF, (seed >> 8) & 0xFF, tx, 0x0D, 0xBF, 0xE6, 0x42, 0x68, 0x41, 0x99, 0x2D, 0x0F, 0xB0, 0x54, 0xBB, 0x16])
    s = int.from_bytes(AES.new(key, AES.MODE_ECB).encrypt(bytes(buf))[0:2], "little")
    return s if s != 0 else 0xFFFF


def decode(data: bytes) -> dict | None:
    """data = the 24 bytes of service data after the UUID F0 08. None if the CRC is wrong."""
    seed = int.from_bytes(data[-4:-2], "little")
    if crc_hqx(bytes(data[:-2]), seed ^ 0xFFFF) != int.from_bytes(data[-2:], "little"):
        return None
    d = bytearray(data[0:2]) + _whiten(data[2:-4], seed & 0xFF, (data[1] & 0x3) << 5) + bytearray(data[-4:-2])
    sign = int.from_bytes(d[17:19], "little")
    return {
        "pfx": d[0:3].hex(), "tx": d[3], "dtype": int.from_bytes(d[4:6], "little"), "id": int.from_bytes(d[6:10], "little"),
        "index": d[10], "cmd": d[11], "b12": d[12], "param": d[13], "arg0": d[14], "arg1": d[15], "arg2": d[16],
        "sign": sign, "sign_ok": sign == 0 or sign == _sign(d[1:17], d[3], seed), "b19": d[19], "seed": seed,
    }


def encode(cmd: int, dev_id: int, index: int, tx: int, seed: int, pfx=(0x10, 0x00, 0x56), dtype=0x0400,
           arg0=0, arg1=0, arg2=0, param=0, with_sign=True) -> bytes:
    """Returns the 24 bytes of service data (to put after the UUID F0 08)."""
    base = bytearray([*pfx, tx & 0xFF, *dtype.to_bytes(2, "little"), *dev_id.to_bytes(4, "little"), index, cmd, 0, param, arg0, arg1, arg2])
    sign = _sign(base[1:17], base[3], seed) if with_sign else 0
    d = base + sign.to_bytes(2, "little") + bytes([0]) + seed.to_bytes(2, "little")
    s8 = seed & 0xFF
    ob = d[:2] + _whiten(d[2:-2], s8, (d[1] & 0x3) << 5) + d[-2:]
    return bytes(ob + crc_hqx(bytes(ob), seed ^ 0xFFFF).to_bytes(2, "little"))
